// Regenerates scripts/test-tiers.json from the last full run's per-file timings
// (test-workspace/testperf/last_parallel.json, last_serial.json and last_load.json, written by npm test).
// The fast tier = files whose top-level tests took under FAST_LIMIT_SEC in the full run,
// minus files that call paid APIs. Usage: npm run test:tiers  (after a full npm test)
import fs from "node:fs";
import path from "node:path";

const FAST_LIMIT_SEC = 15;
// Paid speech/TTS providers or live provider probes: never in the quick loop.
const PAID = new Set([
  "doctor.test.js",
  "ducking_bbox_real_speech.test.js",
  "providers_select.test.js",
  "shared_cache_layout.test.js",
  "speech_cleanup_mix.test.js",
  "transcribe_cache_lang.test.js",
  "verify_cleanup.test.js",
]);

const dir = path.join("test-workspace", "testperf");
const read = (stage) => JSON.parse(fs.readFileSync(path.join(dir, `last_${stage}.json`), "utf8")).files;
const readOptional = (stage) => (fs.existsSync(path.join(dir, `last_${stage}.json`)) ? read(stage) : []);
// A file with "load: " tests appears twice (its other tests + its load tests): add the two times.
const bySum = new Map();
for (const r of [...read("parallel"), ...read("serial"), ...readOptional("load")]) {
  bySum.set(r.file, (bySum.get(r.file) ?? 0) + r.sec);
}
const rows = [...bySum].map(([file, sec]) => ({ file, sec }));
const fast = rows.filter((r) => r.sec < FAST_LIMIT_SEC && !PAID.has(r.file)).map((r) => r.file).sort();
const known = rows.map((r) => r.file).sort();
const out = {
  note: "Generated by scripts/test-tiers.mjs from a full run; do not edit by hand.",
  generated_at: new Date().toISOString(),
  fast_limit_sec: FAST_LIMIT_SEC,
  known,
  fast,
};
fs.writeFileSync(path.join("scripts", "test-tiers.json"), `${JSON.stringify(out, null, 1)}\n`);
const work = rows.filter((r) => fast.includes(r.file)).reduce((a, r) => a + r.sec, 0);
console.log(`fast tier: ${fast.length} of ${known.length} files, ~${Math.round(work)}s of test work`);
